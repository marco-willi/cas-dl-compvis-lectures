"""Export DINOv3 patch features for the hero similarity demo on the welcome page.

Encodes the photos in `assets/images/welcome/` (same model and compression as
`demos/representation_learning/patch_similarity`) and writes `data/<key>.js` (compressed patch
features) and `data/<key>.jpg` (the image) next to `index.html`. Runs on CPU in about
15 seconds.

Usage (from the repository root):

    python demos/welcome/hero_similarity/tools/export_features.py
"""

import base64
import json
from pathlib import Path

import numpy as np
import timm
import torch
from PIL import Image
from timm.data import resolve_data_config

ROOT = Path(__file__).resolve().parents[4]
DEMO_DIR = Path(__file__).resolve().parents[1]
IMAGES_DIR = ROOT / "assets" / "images" / "welcome"
MODEL_ID = "vit_base_patch16_dinov3.lvd1689m"
PATCH_SIZE = 16
DISPLAY_SCALE = 1.5  # display image size relative to the model input
DIMS = 128  # PCA components kept per patch

INPUT_SIZE = (1024, 576)  # (width, height): 64 x 36 patches, 16:9

# key, button label, file, credit, crop box to 16:9 (or None), initial query (x, y as fractions)
IMAGES = [
    (
        "savanna",
        "Savanne",
        "heather-m-edwards-taC5veAcyiA-unsplash.jpg",
        "Heather M. Edwards",
        (0, 120, 1920, 1200),
        (0.40, 0.73),
    ),  # a zebra
]


def patch_features(model, img, size):
    """Return l2-normalized patch tokens of the last block as (patches, dim)."""
    config = resolve_data_config({}, model=model)
    mean, std = np.array(config["mean"]), np.array(config["std"])
    x = (np.asarray(img.resize(size, Image.BICUBIC)) / 255 - mean) / std
    x = torch.tensor(x, dtype=torch.float32).permute(2, 0, 1)[None]
    with torch.no_grad():
        tokens = model.forward_features(x)[0, model.num_prefix_tokens :].numpy()
    return tokens / np.linalg.norm(tokens, axis=-1, keepdims=True)


def compress(x, dims):
    """Project onto the first `dims` (uncentered) principal directions, int8 per row."""
    _, _, vt = np.linalg.svd(x, full_matrices=False)
    z = x @ vt[:dims].T
    return np.round(z * 127 / np.abs(z).max(axis=1, keepdims=True)).astype(np.int8)


def main():
    model = timm.create_model(MODEL_ID, pretrained=True, num_classes=0).eval()
    cols, rows = INPUT_SIZE[0] // PATCH_SIZE, INPUT_SIZE[1] // PATCH_SIZE
    for key, label, fname, credit, crop, initial in IMAGES:
        img = Image.open(IMAGES_DIR / fname).convert("RGB")
        if crop:
            img = img.crop(crop)
        x = patch_features(model, img, INPUT_SIZE)
        assert x.shape[0] == cols * rows

        q = compress(x, DIMS)
        qf = q.astype(np.float32)
        qf /= np.linalg.norm(qf, axis=1, keepdims=True)
        error = np.abs(qf @ qf.T - x @ x.T)

        display = tuple(round(s * DISPLAY_SCALE) for s in INPUT_SIZE)
        img.resize(display, Image.LANCZOS).save(
            DEMO_DIR / "data" / f"{key}.jpg", quality=82
        )

        meta = {
            "model": MODEL_ID,
            "label": label,
            "credit": credit,
            "image": f"data/{key}.jpg",
            "grid": [cols, rows],
            "initial": [int(initial[0] * cols), int(initial[1] * rows)],
            "dims": DIMS,
            "meanError": round(float(error.mean()), 4),
        }
        out = DEMO_DIR / "data" / f"{key}.js"
        out.write_text(
            "// Generated by tools/export_features.py. Do not edit.\n"
            "window.HERO = window.HERO || [];\n"
            f"window.HERO.push({{ meta: {json.dumps(meta)}, "
            f'features: "{base64.b64encode(q.tobytes()).decode()}" }});\n'
        )
        print(
            f"{key}: {cols} x {rows} patches -> {out.name} ({out.stat().st_size / 1e6:.2f} MB), "
            f"cosine error mean {meta['meanError']}"
        )


if __name__ == "__main__":
    main()
