"""Writes data/images.js: the elephant images (base64 JPEG) and a token codebook.

Run from the repository root:
    .venv/bin/python demos/genai_models/image_sampling/tools/build_data.py

The codebook is a k-means clustering of all 16x16 patches of the photos, an illustrative
stand-in for the learned codebook (VQ-VAE) of an autoregressive image model. The demo uses it
only for the distribution over tokens; filled tokens show the photo's own patch.
"""

import base64
import io
import json
from pathlib import Path

import numpy as np
from PIL import Image
from sklearn.cluster import KMeans

ROOT = Path(__file__).resolve().parents[4]
OUT = Path(__file__).resolve().parents[1] / "data" / "images.js"
W, H, PATCH, K, SEED = 256, 144, 16, 24, 7

# image 1 is the canonical example of the lecture; images 2 to 10 were generated with
# tools/generate_images.py (prompts in assets/images/genai_models/image_sampling/prompts.json)
SOURCES = [("savanna", "assets/images/genai/elephant.jpg")] + [
    (
        f"generated_{k:02d}",
        f"assets/images/genai_models/image_sampling/elephant_{k:02d}.jpg",
    )
    for k in range(1, 10)
]


def load(path: Path) -> Image.Image:
    """Center crop to 16:9 and resize to W x H."""
    im = Image.open(path).convert("RGB")
    w, h = im.size
    cw, ch = min(w, round(h * W / H)), min(h, round(w * H / W))
    left, top = (w - cw) // 2, (h - ch) // 2
    return im.crop((left, top, left + cw, top + ch)).resize((W, H), Image.LANCZOS)


def to_data_uri(im: Image.Image) -> str:
    buf = io.BytesIO()
    im.save(buf, format="JPEG", quality=88)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


def patches(a: np.ndarray) -> np.ndarray:
    """(H, W, 3) -> (H/P * W/P, P*P*3), raster order."""
    gh, gw = a.shape[0] // PATCH, a.shape[1] // PATCH
    return (
        a.reshape(gh, PATCH, gw, PATCH, 3).transpose(0, 2, 1, 3, 4).reshape(gh * gw, -1)
    )


images = [(name, load(ROOT / path)) for name, path in SOURCES]
# JPEG round trip, so that the codebook is fitted on the pixels the browser decodes
decoded = [
    np.asarray(
        Image.open(io.BytesIO(base64.b64decode(to_data_uri(im).split(",")[1]))),
        dtype=np.float32,
    )
    for _, im in images
]
kmeans = KMeans(n_clusters=K, n_init=4, random_state=SEED).fit(
    np.concatenate([patches(a) for a in decoded])
)
codebook = np.clip(np.rint(kmeans.cluster_centers_), 0, 255).astype(np.uint8)

data = {
    "width": W,
    "height": H,
    "images": [{"name": name, "src": to_data_uri(im)} for name, im in images],
    "codebook": {
        "patch": PATCH,
        "k": K,
        "data": base64.b64encode(codebook.tobytes()).decode(),
    },
}
OUT.write_text(
    "// Generated by tools/build_data.py, do not edit.\nglobalThis.IMAGE_DATA = "
    + json.dumps(data)
    + ";\n"
)
print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.0f} KB)")
