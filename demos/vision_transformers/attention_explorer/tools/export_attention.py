"""Export ViT self-attention weights for the attention explorer demo.

Runs the same model and image as `demos/vision_transformers/create_vit_illustrations.ipynb`
and writes `data/attention.js` (gzip-compressed, base64-encoded attention weights) and
`data/image.jpg` (the model input) next to `index.html`.

Usage (from the repository root):

    python demos/vision_transformers/attention_explorer/tools/export_attention.py
"""

import base64
import gzip
import json
from pathlib import Path

import numpy as np
import timm
import torch
from PIL import Image
from timm.data import create_transform, resolve_data_config

ROOT = Path(__file__).resolve().parents[4]
DEMO_DIR = Path(__file__).resolve().parents[1]
IMAGE_PATH = (
    ROOT / "assets" / "images" / "vision_transformers" / "archive" / "cows2.jpg"
)
MODEL_ID = "vit_little_patch16_reg4_gap_256.sbb_in1k"
IMG_SIZE = 256
PATCH_SIZE = 16


def attention_weights(model, x):
    """Return softmax attention of every block as (layers, heads, tokens, tokens)."""
    maps = []

    def hook(module, inputs, output):
        B, N, C = inputs[0].shape
        h = module.num_heads
        qkv = module.qkv(inputs[0]).reshape(B, N, 3, h, C // h).permute(2, 0, 3, 1, 4)
        q, k, _ = qkv.unbind(0)
        q, k = module.q_norm(q), module.k_norm(k)
        attn = (q @ k.transpose(-2, -1)) * module.scale
        maps.append(attn.softmax(dim=-1)[0])

    hooks = [b.attn.register_forward_hook(hook) for b in model.blocks]
    with torch.no_grad():
        model(x)
    for h in hooks:
        h.remove()
    return torch.stack(maps).numpy()


def main():
    model = timm.create_model(MODEL_ID, pretrained=True).eval()
    img = (
        Image.open(IMAGE_PATH)
        .convert("RGB")
        .resize((IMG_SIZE, IMG_SIZE), Image.BICUBIC)
    )
    config = resolve_data_config(model.pretrained_cfg)
    config["crop_pct"] = 1.0  # use the full 256 x 256 image, no center crop
    x = create_transform(**config)(img).unsqueeze(0)

    attn = attention_weights(model, x)  # (L, H, N, N)
    layers, heads, tokens, _ = attn.shape
    grid = IMG_SIZE // PATCH_SIZE
    prefix = model.num_prefix_tokens
    assert tokens == prefix + grid * grid

    # Quantize each row (one query) to uint8 relative to its maximum; scales stored as float32.
    row_max = attn.max(axis=-1, keepdims=True)
    quant = np.round(attn / row_max * 255).astype(np.uint8)
    payload = gzip.compress(quant.tobytes(), compresslevel=9, mtime=0)
    scales = row_max[..., 0].astype(np.float32)

    meta = {
        "model": MODEL_ID,
        "image": "data/image.jpg",
        "imageSize": IMG_SIZE,
        "patchSize": PATCH_SIZE,
        "grid": grid,
        "layers": layers,
        "heads": heads,
        "prefixTokens": prefix,
        "tokens": tokens,
        # True for the sbb reg4 models: zero-initialized registers without positional embedding
        # stay identical during training (https://github.com/huggingface/pytorch-image-models/pull/2229).
        "registersIdentical": bool((model.reg_token == model.reg_token[:, :1]).all()),
    }

    img.save(DEMO_DIR / "data" / "image.jpg", quality=90)
    out = DEMO_DIR / "data" / "attention.js"
    out.write_text(
        "// Generated by tools/export_attention.py. Do not edit.\n"
        f"window.ATTENTION_META = {json.dumps(meta)};\n"
        f'window.ATTENTION_SCALES = "{base64.b64encode(scales.tobytes()).decode()}";\n'
        f'window.ATTENTION_GZ = "{base64.b64encode(payload).decode()}";\n'
    )
    print(
        f"{layers} layers x {heads} heads x {tokens}^2 -> {out} ({out.stat().st_size / 1e6:.2f} MB)"
    )


if __name__ == "__main__":
    main()
