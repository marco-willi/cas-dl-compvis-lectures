"""Export DINOv3 patch features for the patch similarity demo.

Encodes the 8 example images of the representation learning lecture (same model as
`demos/representation_learning/representation_comparisons.ipynb`) and writes
`data/features.js` (compressed patch features) and `data/collage.jpg` (the images as one
collage) next to `index.html`. Runs on CPU in about 15 seconds.

Usage (from the repository root):

    python demos/representation_learning/patch_similarity/tools/export_features.py
"""

import base64
import json
from pathlib import Path

import numpy as np
import timm
import torch
from PIL import Image
from timm.data import resolve_data_config

ROOT = Path(__file__).resolve().parents[4]
DEMO_DIR = Path(__file__).resolve().parents[1]
IMAGES_DIR = ROOT / "assets" / "images" / "representation_learning"
MODEL_ID = "vit_base_patch16_dinov3.lvd1689m"
PATCH_SIZE = 16
INPUT_SIZE = (
    640,
    448,
)  # (width, height): 40 x 28 patches, same aspect ratio as the images
TILE_SIZE = (480, 336)  # size of one image in the collage
COLLAGE_COLS = 4
DIMS = 128  # PCA components kept per patch

# Same images, order and titles as @fig-rl-examples in pages/lectures/representation_learning.qmd
IMAGES = [
    ("examples/elephant_day_01.png", "Elephant - Day 1"),
    ("augmented/elephant_flip_horizontal.png", "Elephant - Flipped"),
    ("augmented/elephant_brightness_1_8x.png", "Elephant - Brighter"),
    ("examples/elephant_day_02.png", "Elephant - Day 2"),
    ("examples/giraffe_day_01.png", "Giraffe - Day"),
    ("examples/rhino_night_01.png", "Rhino - Night"),
    ("examples/elephant_night_01.png", "Elephant - Night"),
    ("examples/car_day_01.png", "Car - Day"),
]


def patch_features(model, images):
    """Return l2-normalized patch tokens of the last block as (images, patches, dim)."""
    config = resolve_data_config({}, model=model)
    mean, std = np.array(config["mean"]), np.array(config["std"])
    feats = []
    with torch.no_grad():
        for img in images:
            x = (np.asarray(img.resize(INPUT_SIZE, Image.BICUBIC)) / 255 - mean) / std
            x = torch.tensor(x, dtype=torch.float32).permute(2, 0, 1)[None]
            tokens = model.forward_features(x)[0, model.num_prefix_tokens :]
            feats.append(tokens.numpy())
    feats = np.stack(feats)
    return feats / np.linalg.norm(feats, axis=-1, keepdims=True)


def compress(x, dims):
    """Project onto the first `dims` (uncentered) principal directions, int8 per row.

    Uncentered, so that dot products of the projections approximate the cosine similarities
    of the original features. Each row is scaled to its own maximum; the browser normalizes
    the rows again, so no scales need to be stored.
    """
    _, _, vt = np.linalg.svd(x, full_matrices=False)
    z = x @ vt[:dims].T
    return np.round(z * 127 / np.abs(z).max(axis=1, keepdims=True)).astype(np.int8)


def main():
    model = timm.create_model(MODEL_ID, pretrained=True, num_classes=0).eval()
    images = [Image.open(IMAGES_DIR / path).convert("RGB") for path, _ in IMAGES]

    feats = patch_features(model, images)  # (8, 1120, 768)
    n, patches, dim = feats.shape
    cols, rows = INPUT_SIZE[0] // PATCH_SIZE, INPUT_SIZE[1] // PATCH_SIZE
    assert patches == cols * rows

    x = feats.reshape(-1, dim)
    q = compress(x, DIMS)
    qf = q.astype(np.float32)
    qf /= np.linalg.norm(qf, axis=1, keepdims=True)
    error = np.abs(qf @ qf.T - x @ x.T)

    collage_rows = -(-n // COLLAGE_COLS)
    collage = Image.new(
        "RGB", (TILE_SIZE[0] * COLLAGE_COLS, TILE_SIZE[1] * collage_rows)
    )
    for i, img in enumerate(images):
        r, c = divmod(i, COLLAGE_COLS)
        collage.paste(
            img.resize(TILE_SIZE, Image.LANCZOS), (c * TILE_SIZE[0], r * TILE_SIZE[1])
        )
    collage.save(DEMO_DIR / "data" / "collage.jpg", quality=85)

    meta = {
        "model": MODEL_ID,
        "collage": "data/collage.jpg",
        "collageCols": COLLAGE_COLS,
        "tileSize": TILE_SIZE,
        "inputSize": INPUT_SIZE,
        "patchSize": PATCH_SIZE,
        "grid": [cols, rows],
        "titles": [title for _, title in IMAGES],
        "dims": DIMS,
        "fullDims": dim,
        "meanError": round(float(error.mean()), 4),
        "maxError": round(float(error.max()), 3),
    }
    out = DEMO_DIR / "data" / "features.js"
    out.write_text(
        "// Generated by tools/export_features.py. Do not edit.\n"
        f"window.PATCH_META = {json.dumps(meta)};\n"
        f'window.PATCH_FEATURES = "{base64.b64encode(q.tobytes()).decode()}";\n'
    )
    print(
        f"{n} images x {cols} x {rows} patches x {DIMS} dims -> {out} "
        f"({out.stat().st_size / 1e6:.2f} MB); cosine error mean {meta['meanError']}, max {meta['maxError']}"
    )


if __name__ == "__main__":
    main()
